"$brave/bin/brave-snapshot" "$TMPDIR/captured.json" --user-data-dir="$profile" --profile-directory='Profile 2'
jq -e '.bookmark_bar.show_on_all_tabs and .credentials_enable_service and (has("extensions")|not) and (has("protection")|not) and (has("download")|not) and (has("test_array")|not)' "$TMPDIR/captured.json"
"$brave/bin/brave-sync" --user-data-dir "$profile" --profile-directory 'Profile 2'
jq -e '.credentials_enable_service == false and .bookmark_bar.show_on_all_tabs == true and .extensions.settings.secret == "private"' "$prefs"
# An invalid Preferences file aborts integration-file changes too.
printf '{invalid' > "$prefs"
printf '{"sentinel":true}' > "$profile/External Extensions/nngceckbapebfimnlniiiahkandclblb.json"
if "$brave/bin/brave-sync" --user-data-dir "$profile" --profile-directory 'Profile 2'; then exit 1; fi
jq -e '.sentinel' "$profile/External Extensions/nngceckbapebfimnlniiiahkandclblb.json"
test -s "$profile/Profile 2/.Preferences.sync-error.log"
