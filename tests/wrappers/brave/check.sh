cmp "$TMPDIR/before.json" "$TMPDIR/captured.json"
test -s "$TMPDIR/.captured.json.snapshot-error.log"
# Actual launcher adapter, fake app: sync failure must not suppress app execution.
profile_tool=$(sed -n 's/^exec \([^ ]*\) sync .*$/\1/p' "$brave/bin/brave-sync")
cat > "$TMPDIR/fake-app" <<'SH'
#!/bin/sh
printf '%s\n' "$@" > "$CAPTURE"
exit 23
SH
# The sandbox has no /bin/sh; use the same interpreter as the packaged helper.
head -n 1 "$brave/bin/brave-sync" > "$TMPDIR/fake-executable"
tail -n +2 "$TMPDIR/fake-app" >> "$TMPDIR/fake-executable"
chmod +x "$TMPDIR/fake-executable"
export CAPTURE="$TMPDIR/arguments"
status=0
"$profile_tool" launch "$TMPDIR/fake-executable" --user-data-dir "$profile" --profile-directory 'Profile 2' 'https://example.org/a b' || status=$?
test "$status" = 23
grep -Fx 'https://example.org/a b' "$CAPTURE"
# Open-browser lock preserves even malformed prefs and still launches.
ln -s test-host-123 "$profile/SingletonLock"
status=0
"$profile_tool" launch "$TMPDIR/fake-executable" --user-data-dir "$profile" || status=$?
test "$status" = 23
if "$brave/bin/brave-sync" --user-data-dir "$profile"; then exit 1; fi
rm "$profile/SingletonLock"
# Snapshot must not silently succeed before a profile has produced Preferences.
if "$brave/bin/brave-snapshot" "$TMPDIR/missing.json" --user-data-dir "$TMPDIR/missing-profile"; then exit 1; fi
test ! -e "$TMPDIR/missing.json"
# A snapshot generated by brave-snapshot is embedded in a second wrapper using
# HM flags and a native-host declaration. Explicit settings still win over it.
"$braveRoundtrip/bin/brave-sync" --user-data-dir "$TMPDIR/roundtrip"
jq -e '.bookmark_bar.show_on_all_tabs and .credentials_enable_service == false and (has("extensions")|not)' "$TMPDIR/roundtrip/Default/Preferences"
jq -e '.name == "org.example.test"' "$TMPDIR/roundtrip/NativeMessagingHosts/org.example.test.json"
printf '{"runtime_only":true}' > "$TMPDIR/roundtrip/Default/Preferences"
"$braveRoundtrip/bin/brave-sync" --user-data-dir "$TMPDIR/roundtrip"
jq -e '. == {"runtime_only":true}' "$TMPDIR/roundtrip/Default/Preferences"
# Export must reject symlink leaves rather than overwrite their referents.
printf '{"unchanged":true}' > "$TMPDIR/real.json"
ln -s "$TMPDIR/real.json" "$TMPDIR/link.json"
if "$brave/bin/brave-snapshot" "$TMPDIR/link.json" --user-data-dir "$TMPDIR/roundtrip"; then exit 1; fi
jq -e '.unchanged' "$TMPDIR/real.json"
