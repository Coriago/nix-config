test ! -e "$XDG_CONFIG_HOME/mybrave"
test -f "$profile/External Extensions/nngceckbapebfimnlniiiahkandclblb.json"
test ! -L "$profile/External Extensions/nngceckbapebfimnlniiiahkandclblb.json"
jq -e '.external_update_url == "https://clients2.google.com/service/update2/crx"' "$profile/External Extensions/nngceckbapebfimnlniiiahkandclblb.json"
prefs="$profile/Profile 2/Preferences"
jq -e '.credentials_enable_service == false and .credentials_enable_autosignin == false' "$prefs"
cat > "$prefs" <<'JSON'
{"credentials_enable_service":true,"bookmark_bar":{"show_on_all_tabs":true},"extensions":{"settings":{"secret":"private"}},"protection":{"macs":{"secret":"private"}},"download":{"default_directory":"/home/private/Downloads"},"profile":{"exit_type":"Normal"},"test_array":[{"keep":1,"token":"private"}]}
